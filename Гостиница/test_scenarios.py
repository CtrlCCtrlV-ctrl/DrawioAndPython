class TestScenarios:
    """Класс для выполнения тестовых сценариев"""
    
    def __init__(self):
        self.results = []
        print("=" * 80)
        print("ЗАПУСК ТЕСТОВЫХ СЦЕНАРИЕВ ИС ГОСТИНИЦА")
        print("=" * 80)
        print()
    
    def log_test(self, test_name, step, action, expected, result):
        """Логирование результата теста"""
        status = "✓ PASS" if result else "✗ FAIL"
        self.results.append({
            'test': test_name,
            'step': step,
            'status': result
        })
        print(f"[{status}] Шаг {step}: {action}")
        if not result:
            print(f"   Ожидалось: {expected}")
    
    def test_1_authentication(self):
        """ТЕСТ 1: Проверка авторизации пользователей"""
        print("\n" + "=" * 80)
        print("ТЕСТ 1: Проверка авторизации пользователей")
        print("=" * 80 + "\n")
        
        # Шаг 1: Пустые поля
        result = auth.authenticate("", "")
        self.log_test("Тест 1", 1, "Вход с пустыми полями", 
                     "None", result is None)
        
        # Шаг 2: Неверный пароль
        result = auth.authenticate("admin", "wrongpass")
        self.log_test("Тест 1", 2, "Вход с неверным паролем", 
                     "None", result is None)
        
        # Шаг 3: Корректные данные
        result = auth.authenticate("admin", "admin123")
        self.log_test("Тест 1", 3, "Вход с корректными данными", 
                     "Объект пользователя", result is not None)
        
        # Шаг 4: Проверка роли
        if result:
            auth.set_current_user(result)
            is_admin = result['role'] == 'administrator'
            self.log_test("Тест 1", 4, "Проверка роли администратора", 
                         "administrator", is_admin)
        
        # Шаг 5: Выход
        auth.logout()
        current = auth.get_current_user()
        self.log_test("Тест 1", 5, "Выход из системы", 
                     "None", current is None)
    
    def test_2_bookings_management(self):
        """ТЕСТ 2: Управление номерами и бронирования"""
        print("\n" + "=" * 80)
        print("ТЕСТ 2: Управление номерами и бронирования")
        print("=" * 80 + "\n")
        
        # Шаг 1: Вход как менеджер
        user = auth.authenticate("manager", "manager123")
        self.log_test("Тест 2", 1, "Вход как менеджер", 
                     "Объект пользователя", user is not None)
        
        if not user:
            return
        
        auth.set_current_user(user)
        
        # Загрузка данных
        data_file = Path(__file__).parent / 'data.json'
        with open(data_file, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        # Шаг 2: Проверка списка номеров
        rooms_exist = len(data['rooms']) > 0
        self.log_test("Тест 2", 2, "Открыть список номеров", 
                     "Список номеров", rooms_exist)
        
        # Шаг 3: Проверка доступных номеров
        available_rooms = [r for r in data['rooms'] if r['status'] == 'available']
        has_available = len(available_rooms) > 0
        self.log_test("Тест 2", 3, "Найти доступные номера", 
                     "Есть доступные номера", has_available)
        
        # Шаг 4: Создание тестового бронирования
        if has_available and len(data['guests']) > 0:
            room = available_rooms[0]
            guest = data['guests'][0]
            
            test_booking = {
                "id": "TEST_BOOKING",
                "room_id": room['id'],
                "guest_id": guest['id'],
                "check_in": "2024-03-01",
                "check_out": "2024-03-05",
                "status": "confirmed",
                "total_price": room['price'] * 4,
                "created": datetime.now().strftime("%Y-%m-%d"),
                "created_by": "test"
            }
            
            data['bookings'].append(test_booking)
            original_status = room['status']
            room['status'] = 'occupied'
            
            booking_created = test_booking in data['bookings']
            self.log_test("Тест 2", 4, "Создание бронирования", 
                         "Бронирование создано", booking_created)
            
            # Шаг 5: Отмена бронирования
            data['bookings'] = [b for b in data['bookings'] if b['id'] != 'TEST_BOOKING']
            room['status'] = original_status
            
            booking_cancelled = not any(b['id'] == 'TEST_BOOKING' for b in data['bookings'])
            self.log_test("Тест 2", 5, "Отмена бронирования", 
                         "Бронирование удалено", booking_cancelled)
    
    def test_3_user_management(self):
        """ТЕСТ 3: Управление пользователями (администратор)"""
        print("\n" + "=" * 80)
        print("ТЕСТ 3: Управление пользователями")
        print("=" * 80 + "\n")
        
        # Шаг 1: Вход как администратор
        user = auth.authenticate("admin", "admin123")
        self.log_test("Тест 3", 1, "Вход как администратор", 
                     "Объект пользователя", user is not None and user['role'] == 'administrator')
        
        if not user:
            return
        
        auth.set_current_user(user)
        
        # Шаг 2: Получение списка пользователей
        users = auth.get_all_users()
        self.log_test("Тест 3", 2, "Получить список пользователей", 
                     "Список пользователей", len(users) > 0)
        
        # Шаг 3: Создание нового пользователя
        success, message = auth.create_user("testuser", "testpass123", "guest", "Тестовый Пользователь")
        self.log_test("Тест 3", 3, "Создать нового пользователя",
                     "Успешное создание", success)

        # Шаг 4: Попытка создать дубликат
        success2, message2 = auth.create_user("testuser", "testpass123", "guest", "Тестовый Пользователь")
        self.log_test("Тест 3", 4, "Попытка создать дубликат пользователя",
                     "Ошибка создания", not success2)

        # Шаг 5: Удаление тестового пользователя
        if success:
            auth.delete_user("testuser")
            users_after = auth.get_all_users()
            deleted = not any(u['username'] == 'testuser' for u in users_after)
            self.log_test("Тест 3", 5, "Удаление тестового пользователя",
                         "Пользователь удален", deleted)

    def run_tests(self):
        """Запуск всех тестовых сценариев"""
        print("\n" + "=" * 80)
        print("НАЧАЛО ВСЕХ ТЕСТОВ")
        print("=" * 80 + "\n")

