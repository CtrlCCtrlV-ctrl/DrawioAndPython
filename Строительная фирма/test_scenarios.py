    def run_all_tests(self):
        print("\n")
        print("╔" + "="*78 + "╗")
        print("║" + " "*20 + "ЗАПУСК ТЕСТОВЫХ СЦЕНАРИЕВ" + " "*33 + "║")
        print("║" + " "*15 + "Строительная фирма - Информационная система" + " "*20 + "║")
