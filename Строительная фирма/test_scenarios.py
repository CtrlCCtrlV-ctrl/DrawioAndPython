import json
import sys
import os
from datetime import datetime

# Добавляем путь к модулям
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from auth import AuthManager


class TestScenarios:
    def __init__(self):
        self.auth = AuthManager('users.json')
        self.data_file = 'data.json'
        self.test_results = []
        
    def load_data(self):
        with open(self.data_file, 'r', encoding='utf-8') as f:
            return json.load(f)
    
    def save_data(self, data):
        with open(self.data_file, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

    def reset_data(self):
        # Восстанавливаем исходные данные после тестов
        with open(self.data_file, 'r', encoding='utf-8') as f:
            original_data = json.load(f)
        # Не меняем данные в тестах, просто проверяем что они загружаются правильно
    
    def log_test(self, test_name, step, action, expected, result):
        status = "✓ PASS" if result else "✗ FAIL"
        self.test_results.append({
            'test': test_name,
            'step': step,
            'action': action,
            'expected': expected,
            'status': status
        })
        print(f"{status} | Шаг {step}: {action}")
    
    # ТЕСТ 1: Авторизация
    def test_1_authentication(self):
        print("\n" + "="*80)
        print("ТЕСТ 1: Проверка авторизации пользователей")
        print("="*80)
        
        # Шаг 1: Вход администратором
        success, role = self.auth.login('admin', 'admin')
        self.log_test(
            "Тест 1",
            1,
            "Вход с логином 'admin' и паролем 'admin'",
            "Успешная авторизация как администратор",
            success and role == 'administrator'
        )
        self.auth.logout()
        
        # Шаг 2: Вход менеджером
        success, role = self.auth.login('manager', 'manager')
        self.log_test(
            "Тест 1",
            2,
            "Вход с логином 'manager' и паролем 'manager'",
            "Успешная авторизация как менеджер",
            success and role == 'manager'
        )
        self.auth.logout()
        
        # Шаг 3: Вход клиентом
        success, role = self.auth.login('client', 'client')
        self.log_test(
            "Тест 1",
            3,
            "Вход с логином 'client' и паролем 'client'",
            "Успешная авторизация как клиент",
            success and role == 'client'
        )
        self.auth.logout()
        
        # Шаг 4: Вход с неверным паролем
        success, role = self.auth.login('admin', 'wrongpassword')
        self.log_test(
            "Тест 1",
            4,
            "Вход с неверным паролем",
            "Отказ в авторизации",
            not success
        )
    
    # ТЕСТ 2: Проверка загрузки данных
    def test_2_data_loading(self):
        print("\n" + "="*80)
        print("ТЕСТ 2: Проверка загрузки данных")
        print("="*80)

        # Шаг 1: Авторизация менеджером
        success, role = self.auth.login('manager', 'manager')
        self.log_test(
            "Тест 2",
            1,
            "Авторизация менеджером",
            "Вход в систему успешен",
            success and role == 'manager'
        )

        # Шаг 2: Загрузка данных
        data = self.load_data()
        self.log_test(
            "Тест 2",
            2,
            "Загрузка данных",
            "Данные загружены успешно",
            'projects' in data and 'employees' in data and 'materials' in data
        )

        # Шаг 3: Проверка наличия проектов
        has_projects = len(data['projects']) > 0
        self.log_test(
            "Тест 2",
            3,
            "Проверка наличия проектов",
            "Проекты существуют в системе",
            has_projects
        )

        self.auth.logout()
    
    # ТЕСТ 3: Работа с заявками (клиент)
    def test_3_client_requests(self):
        print("\n" + "="*80)
        print("ТЕСТ 3: Работа с заявками (клиент)")
        print("="*80)

        # Шаг 1: Авторизация клиента
        success, role = self.auth.login('client', 'client')
